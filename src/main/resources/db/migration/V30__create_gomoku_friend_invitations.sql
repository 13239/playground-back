-- 수신자와 대기방마다 진행 중인 초대는 하나만 허용하고 15초 기한을 원본 DB에 보존한다.
CREATE TABLE tbl_gomoku_invitation (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    room_id BIGINT NOT NULL,
    inviter_id BIGINT NOT NULL,
    target_id BIGINT NOT NULL,
    host_membership_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    room_revision BIGINT NOT NULL,
    state VARCHAR(12) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    resolved_at DATETIME(6) NULL,
    accepted_membership_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    pending_room_id BIGINT GENERATED ALWAYS AS (CASE WHEN state = 'PENDING' THEN room_id END) STORED,
    pending_target_id BIGINT GENERATED ALWAYS AS (CASE WHEN state = 'PENDING' THEN target_id END) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uk_gomoku_invitation_public (public_id),
    UNIQUE KEY uk_gomoku_invitation_request (inviter_id, request_id),
    UNIQUE KEY uk_gomoku_invitation_pending_room (pending_room_id),
    UNIQUE KEY uk_gomoku_invitation_pending_target (pending_target_id),
    KEY idx_gomoku_invitation_target (target_id, state, expires_at),
    KEY idx_gomoku_invitation_inviter (inviter_id, state, expires_at),
    KEY idx_gomoku_invitation_room (room_id, state),
    KEY idx_gomoku_invitation_recovery (state, id),
    CONSTRAINT fk_gomoku_invitation_room FOREIGN KEY (room_id) REFERENCES tbl_gomoku_room(id),
    CONSTRAINT fk_gomoku_invitation_inviter FOREIGN KEY (inviter_id) REFERENCES tbl_user(id),
    CONSTRAINT fk_gomoku_invitation_target FOREIGN KEY (target_id) REFERENCES tbl_user(id),
    CONSTRAINT ck_gomoku_invitation_self CHECK (inviter_id <> target_id),
    CONSTRAINT ck_gomoku_invitation_state CHECK (state IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_gomoku_invitation_deadline CHECK (expires_at > created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
